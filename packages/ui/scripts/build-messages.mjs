// Message catalog build: src/i18n/catalogs/<group>.<locale>.json -> src/i18n/catalogs.generated.ts
//
// Copy is ICU MessageFormat from day one (docs/04-design-plan.md section 8). en-AU is the base locale;
// the generated union type of its keys types every `t()` call. Groups are separate files so streams and
// reviewers (the designer, receipt and KDS copy owners) can work on their own catalog.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { IntlMessageFormat } from 'intl-messageformat';
import { format, resolveConfig } from 'prettier';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'src/i18n/catalogs');
const out = join(root, 'src/i18n/catalogs.generated.ts');
const check = process.argv.includes('--check');
const BASE = 'en-AU';

/** @type {Record<string, Record<string, string>>} */
const byLocale = {};
/** @type {Record<string, string>} */
const keyOwner = {};
const errors = [];

for (const file of readdirSync(dir)
  .filter((f) => f.endsWith('.json'))
  .sort()) {
  const match = /^(?<group>[a-z0-9-]+)\.(?<locale>[A-Za-z]{2,3}(?:-[A-Za-z0-9]+)*)\.json$/.exec(
    file,
  );
  if (!match?.groups) {
    errors.push(`${file}: expected <group>.<locale>.json`);
    continue;
  }
  const { group, locale } = match.groups;
  const messages = JSON.parse(readFileSync(join(dir, file), 'utf8'));
  byLocale[locale] ??= {};
  for (const [key, value] of Object.entries(messages)) {
    if (typeof value !== 'string') {
      errors.push(`${file}: ${key} is not a string`);
      continue;
    }
    const id = `${locale}:${key}`;
    if (keyOwner[id]) errors.push(`${file}: duplicate key ${key} (also in ${keyOwner[id]})`);
    keyOwner[id] = file;
    try {
      new IntlMessageFormat(value, locale);
    } catch (error) {
      errors.push(`${file}: ${key} is not valid ICU MessageFormat: ${error.message}`);
    }
    byLocale[locale][key] = value;
  }
  void group;
}

const base = byLocale[BASE] ?? {};
for (const [locale, messages] of Object.entries(byLocale)) {
  if (locale === BASE) continue;
  for (const key of Object.keys(messages)) {
    if (!(key in base)) errors.push(`${locale}: key ${key} does not exist in ${BASE}`);
  }
}
if (errors.length > 0) {
  console.error(errors.join('\n'));
  process.exit(1);
}

const sorted = Object.fromEntries(
  Object.entries(byLocale).map(([locale, messages]) => [
    locale,
    Object.fromEntries(Object.entries(messages).sort(([a], [b]) => a.localeCompare(b))),
  ]),
);
const source = `/* GENERATED by scripts/build-messages.mjs from src/i18n/catalogs/*.json. Do not edit by hand. */

export const catalogs = ${JSON.stringify(sorted, null, 2)} as const;

export type MessageKey = keyof (typeof catalogs)['${BASE}'];
export type CatalogLocale = keyof typeof catalogs;
export const baseLocale = '${BASE}' as const;
`;
const rc = (await resolveConfig(out)) ?? {};
const formatted = await format(source, { ...rc, parser: 'typescript' });

if (check) {
  let current = '';
  try {
    current = readFileSync(out, 'utf8');
  } catch {
    /* missing counts as stale */
  }
  if (current !== formatted) {
    console.error('stale: src/i18n/catalogs.generated.ts. Run: pnpm --filter @pos/ui messages');
    process.exit(1);
  }
  console.log('message catalogs are up to date');
} else {
  writeFileSync(out, formatted);
  console.log(
    `wrote src/i18n/catalogs.generated.ts (${Object.keys(base).length} ${BASE} messages)`,
  );
}
